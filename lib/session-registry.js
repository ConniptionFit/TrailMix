/**
 * In-memory session registry — single source of truth in main process.
 */
const sessionRegistry = new Map();

function getSession(sessionId) {
  return sessionRegistry.get(sessionId) || null;
}

function setSession(session) {
  if (!session?.id) return null;
  sessionRegistry.set(session.id, session);
  return session;
}

function deleteSession(sessionId) {
  sessionRegistry.delete(sessionId);
}

function createNewSession({ encryptByDefault = false } = {}) {
  const session = {
    id: `call_${Date.now()}`,
    date: new Date().toLocaleString(),
    title: 'New Meeting',
    titleAutoGenerated: true,
    titleUserEdited: false,
    description: '',
    transcript: [],
    summary: '',
    actionItems: '',
    mixNotes: '',
    enhancedNotes: '',
    editorDocument: null,
    tags: [],
    suggestedTags: [],
    encrypted: encryptByDefault
  };
  return setSession(session);
}

function applyAutoTitle(session, title, description, tags = []) {
  if (!session) return session;
  if (session.titleUserEdited) return session;
  if (!session.titleAutoGenerated) return session;
  session.title = title || session.title;
  session.description = description || session.description;
  session.suggestedTags = tags;
  return session;
}

module.exports = {
  sessionRegistry,
  getSession,
  setSession,
  deleteSession,
  createNewSession,
  applyAutoTitle
};
